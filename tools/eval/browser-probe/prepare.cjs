#!/usr/bin/env node
/*
 * Freezes the exact grid-intent-v2 prompt for the browser probe.
 *
 * The probe must send *byte-identical* input to what the Node run sent, or the
 * two latency figures are not comparable — which is the whole point of
 * reusing grid-001. So the prompt is generated here, by the real builder
 * against the real fixture and the real contract, and written to disk. The
 * browser fetches it rather than rebuilding it, because rebuilding it in the
 * browser would mean a second code path and a second chance to differ.
 *
 * Run: node tools/eval/browser-probe/prepare.cjs
 */

const fs = require("fs");
const path = require("path");

require("../../ts-require.cjs").register();

const harness = require("../harness.ts");
const { GRID_OPERATIONS } = require("../../../source/beta-components/data-grid/agent/index.ts");
const { buildPrompt } = require("../grid/prompt.cjs");
const { CORPUS_VERSION } = require("../grid/runner.cjs");

const CASE_ID = "grid-001";

const fixture = harness.loadFixture();
const entry = harness.loadCases().find((c) => c.id === CASE_ID);
if (!entry) throw new Error(`${CASE_ID} is not in the corpus`);

const { agent } = harness.mount(fixture);
const contract = agent.contract();
const responseSchema = agent.responseSchema();

const prompt = buildPrompt({
  contract,
  responseSchema,
  operations: GRID_OPERATIONS,
  utterance: entry.utterance,
  version: "v2",
});

const payload = {
  $comment:
    "Generated by tools/eval/browser-probe/prepare.cjs. Do not hand-edit — the browser " +
    "probe is only comparable with the Node run while this is byte-identical to it.",
  corpusVersion: CORPUS_VERSION,
  promptVersion: prompt.promptVersion,
  contractVersion: contract.contractVersion,
  case: { id: entry.id, utterance: entry.utterance, expected: entry.intents },
  system: prompt.system,
  user: prompt.user,
  responseSchema,
  fixture,
};

const out = path.join(__dirname, "prompt.json");
fs.writeFileSync(out, `${JSON.stringify(payload, null, 2)}\n`);

console.log(`wrote ${path.relative(harness.ROOT, out)}`);
console.log(`  case          ${payload.case.id} — ${JSON.stringify(payload.case.utterance)}`);
console.log(`  promptVersion ${payload.promptVersion}`);
console.log(`  corpusVersion ${payload.corpusVersion}`);
console.log(`  system        ${prompt.system.length} chars`);
console.log(`  expected      ${JSON.stringify(payload.case.expected)}`);
